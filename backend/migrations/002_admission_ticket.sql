CREATE TABLE IF NOT EXISTS `ticket_verification_record` (
  `id` bigint NOT NULL,
  `update_time` datetime(3) DEFAULT NULL,
  `create_time` datetime(3) DEFAULT NULL,
  `delete_time` datetime(3) DEFAULT NULL,
  `ticket_id` bigint DEFAULT NULL,
  `success_ticket_id` bigint DEFAULT NULL,
  `organizer_id` bigint NOT NULL,
  `operator_user_id` bigint NOT NULL,
  `credential_fingerprint` varchar(64) NOT NULL,
  `result` varchar(32) NOT NULL,
  `detail` varchar(256) DEFAULT NULL,
  `verified_at` datetime(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `idx_ticket_verification_record_success_ticket_id` (`success_ticket_id`),
  KEY `idx_ticket_verification_record_delete_time` (`delete_time`),
  KEY `idx_ticket_verification_record_ticket_id` (`ticket_id`),
  KEY `idx_ticket_verification_record_organizer_id` (`organizer_id`),
  KEY `idx_ticket_verification_record_operator_user_id` (`operator_user_id`),
  KEY `idx_ticket_verification_record_credential_fingerprint` (`credential_fingerprint`),
  KEY `idx_ticket_verification_record_result` (`result`),
  KEY `idx_ticket_verification_record_verified_at` (`verified_at`),
  CONSTRAINT `fk_verification_ticket` FOREIGN KEY (`ticket_id`) REFERENCES `admission_ticket` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
